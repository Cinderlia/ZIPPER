package bee.zipper.core.analysis.aliasing

import bee.zipper.core.analysis.graph.icfg.*
import bee.zipper.core.analysis.vsa.ValueSetResult
import bee.zipper.core.ir.CpgNodeExtension.*
import io.joern.dataflowengineoss.queryengine.AccessPathUsage
import io.shiftleft.codepropertygraph.generated.nodes.*
import io.shiftleft.semanticcpg.accesspath.MatchResult
import io.shiftleft.semanticcpg.language.*
import io.shiftleft.semanticcpg.language.operatorextension.allAssignmentTypes
import io.shiftleft.semanticcpg.utils.MemberAccess.isFieldAccess
import org.slf4j.LoggerFactory

import java.util.concurrent.ConcurrentHashMap
import scala.collection.mutable

class DefaultAliasAnalysis(vsa: ValueSetResult, icfg: ICfg, maxDepth: Int = 5) extends AliasFinder {
  private val logger = LoggerFactory.getLogger(this.getClass)
  private val cache  = new ConcurrentHashMap[CfgNode, List[CfgNode]]()

  def find(node: CfgNode): List[CfgNode] = {
    val alias = cache.computeIfAbsent(node, key => impl(key))
    logger.info(s"aliasOf(${node.log}) = ${alias.map(_.log)}")
    alias
  }

  private def impl(node: CfgNode): List[CfgNode] = {
    if (isJoernTempVar(node)) {
      return List.empty
    }
    val worklist  = mutable.Queue.empty[(CfgNode, Int)]
    val visited   = mutable.Set.empty[CfgNode]
    val aliasList = mutable.ListBuffer.empty[CfgNode]
    worklist += ((node, 1))
    while (worklist.nonEmpty) {
      val (current, depth) = worklist.dequeue()
      if (!visited.contains(current) && depth <= maxDepth) {
        visited += current
        meetAlias(node, current) match {
          case Some(alias) => aliasList += alias
          case _ =>
            val inEdges = icfg.getInEdgesOf(current)
            inEdges.foreach {
              case e: ICfgCallEdge => worklist += ((e.from, depth + 1))
              case e: ICfgRetEdge  => worklist += ((e.from, depth - 1))
              case e @ _           => worklist += ((e.from, depth))
            }
        }
      }
    }
    aliasList.distinct.toList
  }

  // variable generated by statement lowering, such as `list($x, $y) = $array`
  private def isJoernTempVar(node: CfgNode): Boolean = node.code.contains("tmp")

  private val classFamilyCache = mutable.Map.empty[TypeDecl, Set[TypeDecl]]

  private def isInSameClassFamily(node1: CfgNode, node2: CfgNode): Boolean = {
    def getClassFamily(typeDecl: TypeDecl): Set[TypeDecl] = {
      // copy from CallLinkerPassBase.scala
      classFamilyCache.getOrElseUpdate(
        typeDecl, {
          val all = typeDecl :: typeDecl.referencingType
            .flatMap(typ => typ._inheritsFromIn.flatMap { case sub: TypeDecl => sub.flatMap(getClassFamily) })
            .toList
          all.toSet
        }
      )
    }

    def getTypeDecl(node: CfgNode): Option[TypeDecl] = node.method.typeDecl

    (getTypeDecl(node1), getTypeDecl(node2)) match {
      case (Some(typeDecl1), Some(typeDecl2)) =>
        val family1 = getClassFamily(typeDecl1)
        val family2 = getClassFamily(typeDecl2)
        family1.intersect(family2).nonEmpty
      case _ => false
    }
  }

  private def isFetchedByThis(node: CfgNode): Boolean = node.code.contains("$this")

  private def meetAlias(base: CfgNode, node: CfgNode): Option[CfgNode] = {
    node match {
      case call: Call if allAssignmentTypes.contains(call.name) =>
        (call.argumentOption(1), call.argumentOption(2)) match {
          case (Some(target: Call), Some(source)) if isFieldAccess(target.name) =>
            Option.when(isSame(base, target))(source)
          case _ => None
        }
      case _ =>
        None
    }
  }

  private def isSame(a: CfgNode, b: CfgNode): Boolean = {
    val (aBase, aPath)   = AccessPathUsage.toTrackedBaseAndAccessPathSimple(a)
    val (bBase, bPath)   = AccessPathUsage.toTrackedBaseAndAccessPathSimple(b)
    val isAccessPathSame = aBase == bBase && aPath.matchAndDiff(bPath.elements)._1 == MatchResult.EXACT_MATCH
    if (!isAccessPathSame) false
    else if (!isFetchedByThis(a)) true
    else
      isInSameClassFamily(a, b) // check whether the typeDecl family of `$this->xxx` have intersection
  }
}
